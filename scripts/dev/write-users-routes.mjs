// v1.85.1 (D-413): writes lib/routing/users-routes.ts, the list of every page
// address under /users, read from the app/users folders. The middleware answers
// any other /users address with the real 404 (the @pane catch-all slot from
// v1.83.0 otherwise makes every /users address a route). Runs before every
// build (npm "prebuild"); tests/routing/users-routes.test.ts fails when the
// committed copy is out of date. Run: node scripts/dev/write-users-routes.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(ROOT, "lib", "routing", "users-routes.ts");

// Folder name → pattern piece; null = the folder adds nothing to the address.
function piece(name) {
  if (/^\(.*\)$/.test(name)) return null; // (group)
  if (/^\[\[\.\.\..+\]\]$/.test(name)) return "(?:/[^/]+)*"; // [[...optional]]
  if (/^\[\.\.\..+\]$/.test(name)) return "(?:/[^/]+)+"; // [...catchAll]
  if (/^\[.+\]$/.test(name)) return "/[^/]+"; // [id]
  return `/${name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`;
}

export function usersRoutePatterns(root = ROOT) {
  const patterns = new Set();
  const walk = (dir, prefix) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.isFile() && /^(page|route)\.(tsx|ts|jsx|js)$/.test(entry.name)) patterns.add(`^/users${prefix}$`);
      if (!entry.isDirectory()) continue;
      // @slots, _private folders and (.)intercepting routes have no address of their own.
      if (/^[@_]/.test(entry.name) || /^\(\.+\)/.test(entry.name)) continue;
      // v1.89.0 (D-423, UIQA-LAY-03): app/users/[...unknown] answers an address no page has
      // (the area's 404 inside the shell); it is not a page address itself.
      if (dir === path.join(root, "app", "users") && entry.name === "[...unknown]") continue;
      const part = piece(entry.name);
      walk(path.join(dir, entry.name), part === null ? prefix : prefix + part);
    }
  };
  walk(path.join(root, "app", "users"), "");
  return [...patterns].sort();
}

export function usersRoutesSource(patterns = usersRoutePatterns()) {
  return [
    "// GENERATED by scripts/dev/write-users-routes.mjs (v1.85.1, D-413). Do not edit by hand:",
    "// run `node scripts/dev/write-users-routes.mjs` (npm run build does it first).",
    "// Every page address under /users; the middleware gives any other /users address the real 404.",
    "export const USERS_ROUTE_PATTERNS: readonly string[] = [",
    ...patterns.map((pattern) => `  ${JSON.stringify(pattern)},`),
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = usersRoutesSource();
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
  if (now !== next) fs.writeFileSync(OUT, next);
  console.log(`users routes: ${usersRoutePatterns().length} page addresses${now === next ? " (unchanged)" : " written"}`);
}
